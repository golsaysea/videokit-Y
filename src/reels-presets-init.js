function getSubtitlePresetCode(presetName) {
    if (!presetName) return '';
    return REELS_PRESET_NAME_TO_ID[String(presetName).trim()] || '';
}
function formatSubtitlePresetDisplayName(presetName) {
    const raw = String(presetName || '').trim();
    if (!raw) return '';
    const code = getSubtitlePresetCode(raw);
    if (!code || raw.startsWith(`[${code}]`)) return raw;
    return `[${code}] ${raw}`;
}

