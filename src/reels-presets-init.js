function resolveBuiltinPreset(idOrName) {
    let key = String(idOrName || '').trim();
    if (!key) return null;
    const bracketMatch = key.match(/^\[([a-z]+-\d+)\]\s*(.*)$/i);
    if (bracketMatch) {
        const bracketCode = bracketMatch[1].toLowerCase();
        const bracketName = bracketMatch[2].trim();
        if (REELS_PRESET_ID_MAP[bracketCode] || REELS_SCROLL_PRESET_ID_MAP[bracketCode] || REELS_OVERLAY_PRESET_ID_MAP[bracketCode]) {
            key = bracketCode;
        } else if (bracketName) {
            key = bracketName;
        }
    }
    if (REELS_BUILTIN_PRESETS[key]) {
        return { kind: 'subtitle', id: key, name: key, preset: REELS_BUILTIN_PRESETS[key] };
    }
    const mappedSubName = REELS_PRESET_ID_MAP[key] || REELS_PRESET_ID_MAP[key.toLowerCase()];
    if (mappedSubName && REELS_BUILTIN_PRESETS[mappedSubName]) {
        return { kind: 'subtitle', id: key, name: mappedSubName, preset: REELS_BUILTIN_PRESETS[mappedSubName] };
    }
    if (REELS_BUILTIN_OVERLAY_GROUP_PRESETS[key]) {
        return { kind: 'overlay', id: key, name: key, overlays: REELS_BUILTIN_OVERLAY_GROUP_PRESETS[key] };
    }
    const mappedOvName = REELS_OVERLAY_PRESET_ID_MAP[key] || REELS_OVERLAY_PRESET_ID_MAP[key.toLowerCase()];
    if (mappedOvName && REELS_BUILTIN_OVERLAY_GROUP_PRESETS[mappedOvName]) {
        return { kind: 'overlay', id: key, name: mappedOvName, overlays: REELS_BUILTIN_OVERLAY_GROUP_PRESETS[mappedOvName] };
    }
    if (REELS_BUILTIN_SCROLL_STYLE_PRESETS[key]) {
        const sc = REELS_BUILTIN_SCROLL_STYLE_PRESETS[key];
        return {
            kind: 'scroll_style',
            id: sc.preset_id || key,
            name: key,
            category: sc.category || '经典描边滚动',
            style: sc,
            overlays: [{ ...sc, type: 'scroll' }],
        };
    }
    const mappedScrollName = REELS_SCROLL_PRESET_ID_MAP[key] || REELS_SCROLL_PRESET_ID_MAP[key.toLowerCase()];
    if (mappedScrollName && REELS_BUILTIN_SCROLL_STYLE_PRESETS[mappedScrollName]) {
        const sc = REELS_BUILTIN_SCROLL_STYLE_PRESETS[mappedScrollName];
        return {
            kind: 'scroll_style',
            id: sc.preset_id || key.toLowerCase(),
            name: mappedScrollName,
            category: sc.category || '经典描边滚动',
            style: sc,
            overlays: [{ ...sc, type: 'scroll' }],
        };
    }
    return null;
}

